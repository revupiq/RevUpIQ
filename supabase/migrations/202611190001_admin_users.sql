-- Admin panel accounts besides the built-in "admin" login (the owner). Each one
-- signs in with its own username and password and sees only the sections in
-- `sections` (keys from Infrastructure/AdminAccess.cs, e.g. 'users', 'faqs').
-- Only the owner manages them, on the panel's Admin Users page.
--
-- Passwords are stored as ASP.NET Core Identity hashes (PBKDF2), never as text.
-- Only the service role (the admin panel's server) reads or writes the table.
begin;

create table public.admin_users (
  id bigint generated by default as identity primary key,
  username text not null check (username ~ '^[A-Za-z0-9._-]{3,40}$'),
  password_hash text not null,
  sections text[] not null default '{}',
  is_active boolean not null default true,
  last_login_at timestamptz,
  created_at timestamptz not null default pg_catalog.now(),
  updated_at timestamptz not null default pg_catalog.now()
);

-- One account per name, whatever the letter case
create unique index admin_users_username_key on public.admin_users (pg_catalog.lower(username));

alter table public.admin_users enable row level security;
revoke all on public.admin_users from anon, authenticated;

commit;
